ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS classificacao TEXT DEFAULT '16 anos';

CREATE TABLE IF NOT EXISTS public.inscricoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT REFERENCES public.eventos(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    setor_ingresso TEXT DEFAULT 'Pista Rock',
    codigo_confirmacao TEXT NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha TEXT NOT NULL DEFAULT 'rock2026',
    papel TEXT NOT NULL DEFAULT 'administrador',
    status TEXT NOT NULL DEFAULT 'ativo',
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

